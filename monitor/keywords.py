def norm(t: str) -> str:
    t = (t or "").lower().replace("ё", "е").replace("’", "'").replace("ʼ", "'").replace("`", "'")
    return re.sub(r"\s+", " ", t)


def stem(w: str) -> str:
    w = norm(w).strip("'-")
    if len(w) <= 3:
        return w
    if len(w) == 4:
        return w[:3] if w[-1] in "аяоеєуюіиыь" else w      # «море» → «мор», «парк» → «парк»
    s = _END.sub("", w)
    if len(s) >= 5:
        s = _END.sub("", s)          # другий прохід: «дизайнерськими» → «дизайнерськ»
    return s if len(s) >= 3 else w[:4]


def word_variants(w: str):
    st = stem(w)
    out = {st}
    for uk, ru in UK_RU.items():
        if st.startswith(uk) or uk.startswith(st):
            out.add(ru)
        if st.startswith(ru) or ru.startswith(st):
            out.add(uk)
    return [v for v in out if v]


@lru_cache(maxsize=512)
def compile_keyword(kw: str):
    """Повертає функцію text -> bool і короткий опис (для пояснення користувачу)."""
    k = norm(kw).strip()
    for name, c in CONCEPTS.items():
        if any(k == norm(t) or (len(k) > 6 and len(norm(t)) > 6 and norm(t) in k) for t in c["triggers"]):
            pats = [re.compile(p) for p in c["patterns"]]
            return (lambda text, pats=pats: any(p.search(text) for p in pats)), name
    words = [w for w in re.findall(r"[\w'’-]+", k) if w not in STOP]
    if not words:
        return (lambda text, k=k: k in text), "literal"
    groups = []
    for w in words:
        vs = word_variants(w)
        groups.append(re.compile(r"(?<!\w)(?:" + "|".join(re.escape(v) for v in sorted(vs, key=len, reverse=True)) + r")"))
    return (lambda text, groups=groups: all(g.search(text) for g in groups)), "words"


def matches(keyword: str, text: str) -> bool:
    fn, _ = compile_keyword(keyword)
    return fn(norm(text))


def explain(keyword: str) -> str:
    _, kind = compile_keyword(keyword)
    return {"literal": "дослівно", "words": "усі слова в будь-якій формі"}.get(kind, "поняття")
